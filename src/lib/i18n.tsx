const DICTS: Record<Lang, Record<TranslationKey, string>> = { en, ar, sv };

function interpolate(text: string, vars?: Record<string, string | number>) {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, k) =>
    vars[k] === undefined ? m : String(vars[k]),
  );
}

type Ctx = {
  lang: Lang;
  dir: "ltr" | "rtl";
  locale: string;
  setLang: (lang: Lang) => void;
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string;
  /** Translate a dynamic value, falling back to the raw text when unknown. */
  tx: (key: string, fallback: string) => string;
};

const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    try {
      const stored = window.localStorage.getItem(KEY) as Lang | null;
      if (stored && stored in DICTS) setLangState(stored);
    } catch {
      /* ignore */
    }
  }, []);

  const meta = LANGUAGES.find((l) => l.code === lang) ?? LANGUAGES[0];

  useEffect(() => {
    if (typeof document === "undefined") return;
    document.documentElement.lang = lang;
    document.documentElement.dir = meta.dir;
  }, [lang, meta.dir]);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    try {
      window.localStorage.setItem(KEY, next);
    } catch {
      /* ignore */
    }
  }, []);

  const t = useCallback(
    (key: TranslationKey, vars?: Record<string, string | number>) =>
      interpolate(DICTS[lang]?.[key] ?? en[key] ?? key, vars),
    [lang],
  );

  const tx = useCallback(
    (key: string, fallback: string) => {
      const dict = DICTS[lang] as Record<string, string>;
      return dict[key] ?? (en as Record<string, string>)[key] ?? fallback;
    },
    [lang],
  );

  const value = useMemo(
    () => ({ lang, dir: meta.dir as "ltr" | "rtl", locale: meta.locale, setLang, t, tx }),
    [lang, meta.dir, meta.locale, setLang, t, tx],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
